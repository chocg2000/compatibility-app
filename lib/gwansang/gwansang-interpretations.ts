// ============================================================================
// 조합: Stage 2(analyzer.ts) 판정 결과를 스니펫과 매칭해 하나의 해석 문단으로 합친다
// ============================================================================

/** 문장을 이어붙일 때 앞에 붙이는 접속어. 문장 수가 많아도 단조롭지 않도록 순환시킨다. */
const CONNECTIVES = ["또한", "그리고", "동시에", "여기에", "아울러", "더불어"];

function joinAsParagraph(sentences: string[]): string {
  return sentences
    .map((sentence, index) => (index === 0 ? sentence : `${CONNECTIVES[(index - 1) % CONNECTIVES.length]} ${sentence}`))
    .join(" ");
}

interface SnippetLookupKey {
  part: string;
  label: string;
}

/**
 * analyzer.ts의 판정 결과를 gwansangInterpretations의 "부위/라벨" 키로 변환한다.
 * 부위 순서는 이마 → 눈 → 코 → 입술 → 턱 → 눈썹 → 안색으로 고정한다.
 *
 * analyzer.ts가 쓰는 원자적 라벨(예: "높다", "쌍꺼풀")과 이 파일의 스니펫 키
 * (예: "콧대 높다", "쌍꺼풀 있음")가 문자열 그대로 일치하지 않는 부위는 여기서
 * 맞춰준다. "판단 어려움"이나 이중턱 "없음"처럼 스니펫이 없는 판정은 아예 키를
 * 추가하지 않아, 아래 collectSnippets에서 자연스럽게 생략된다.
 */
function collectLookupKeys(geometry: GwansangGeometryAnalysis): SnippetLookupKey[] {
  const keys: SnippetLookupKey[] = [
    { part: "이마", label: geometry.forehead.shape },
    { part: "눈", label: geometry.eyes.size },
    { part: "눈", label: geometry.eyes.tilt },
  ];

  if (geometry.eyes.eyelid === "쌍꺼풀") {
    keys.push({ part: "눈", label: "쌍꺼풀 있음" });
  } else if (geometry.eyes.eyelid === "무쌍꺼풀") {
    keys.push({ part: "눈", label: "쌍꺼풀 없음" });
  }
  // eyelid === "판단 어려움"이면 아무 키도 추가하지 않는다 - 눈꺼풀 판정 자체를 생략.

  keys.push(
    { part: "코", label: `콧대 ${geometry.nose.bridgeHeight}` },
    { part: "코", label: `코끝 ${geometry.nose.tipShape}` },
    { part: "입술", label: geometry.mouth.lipThickness },
    { part: "입술", label: geometry.mouth.mouthSize },
    { part: "턱", label: geometry.chin.jawShape },
  );

  if (geometry.chin.doubleChin === "있음") {
    keys.push({ part: "턱", label: "이중턱" });
  }
  // doubleChin === "없음"은 별도로 언급할 특징이 아니므로 생략한다.

  keys.push(
    { part: "눈썹", label: geometry.eyebrows.thickness },
    { part: "눈썹", label: geometry.eyebrows.shape },
    { part: "안색", label: geometry.complexion.tone },
  );

  return keys;
}

/**
 * 키에 해당하는 스니펫을 찾아 순서대로 모은다.
 * gwansangInterpretations는 문자열 Record라 타입으로 존재를 보장할 수 없으므로,
 * 매칭되지 않는 키(판정 실패, 또는 스니펫 데이터에 아직 없는 라벨)는 조용히 걸러낸다 -
 * 이 필터링이 "판정 실패한 부위를 자연스럽게 생략"하는 지점이다.
 */
function collectSnippets(geometry: GwansangGeometryAnalysis): GwansangSnippet[] {
  return collectLookupKeys(geometry)
    .map(({ part, label }) => gwansangInterpretations[part]?.[label])
    .filter((snippet): snippet is GwansangSnippet => snippet !== undefined);
}

/** composeGwansangInterpretation()의 반환 형태 - 세 관점 각각이 하나의 문단이다. */
export interface GwansangComposedInterpretation {
  /** 성격 */
  성격: string;
  /** 직업/적성 */
  "직업/적성": string;
  /** 연애운 */
  연애운: string;
}

/**
 * Stage 2(analyzer.ts)가 판정한 부위별 라벨에 해당하는 스니펫을 모아,
 * 성격/직업·적성/연애운 세 관점 각각을 하나의 자연스러운 문단으로 합친다.
 *
 * 부위 순서(이마→눈→코→입술→턱→눈썹→안색)대로 문장을 나열하되, 접속어
 * (또한/그리고/동시에 ...)를 앞에 붙여 단순 나열이 아니라 이어지는 글처럼 읽히게 한다.
 * "판단 어려움" 같은 판정 실패 항목은 애초에 스니펫이 없어 문단에서 빠진다.
 */
export function composeGwansangInterpretation(
  geometry: GwansangGeometryAnalysis,
): GwansangComposedInterpretation {
  const snippets = collectSnippets(geometry);

  return {
    성격: joinAsParagraph(snippets.map((s) => s.성격)),
    "직업/적성": joinAsParagraph(snippets.map((s) => s["직업/적성"])),
    연애운: joinAsParagraph(snippets.map((s) => s.연애운)),
  };
}

/** 관상 개별분석 화면(및 통합 프로필)이 다루는 최종 결과 형태 - 기하 판정 + 해석 문단. */
export interface GwansangAnalysisResult {
  geometry: GwansangGeometryAnalysis;
  interpretation: GwansangComposedInterpretation;
}
