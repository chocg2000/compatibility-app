import { getHanjaJawonStrokeCount, getHanjaStrokeCount } from "./stroke-count";

/**
 * 이름에 흔히 쓰이는 한자 하나의 사전 정보.
 * 필획/원획은 하드코딩하지 않고 stroke-count.ts의 계산 로직을 그대로 재사용한다.
 */
export interface HanjaDictionaryEntry {
  한자: string;
  훈: string;
  필획: number;
  원획: number;
}

function entry(한자: string, 훈: string): HanjaDictionaryEntry {
  return { 한자, 훈, 필획: getHanjaStrokeCount(한자), 원획: getHanjaJawonStrokeCount(한자) };
}

